RULE_FIELDS = ("mccmnc_tuple", "imsi_prefix_xpattern", "iccid_prefix", "gid1", "gid2",
               "plmn", "spn", "privilege_access_rule", "preferred_apn")


class Rule:
    def __init__(self, cid, name, parent, values):
        self.cid, self.name, self.parent = cid, name, parent
        self.mccmnc, self.imsi, self.iccid, self.gid1, self.gid2, self.plmn, self.spn, \
            self.priv, self.apn = values


def parse_carrier_ids(path: pathlib.Path):
    text = path.read_text(encoding="utf-8")
    names: dict[int, str] = {}
    rules: list[Rule] = []
    for block in re.findall(r"^carrier_id \{\n(.*?)^\}", text, re.S | re.M):
        cid = int(re.search(r"^  canonical_id: (\d+)", block, re.M).group(1))
        name_m = re.search(r'^  carrier_name: "(.*)"', block, re.M)
        name = name_m.group(1) if name_m else ""
        parent_m = re.search(r"^  parent_canonical_id: (\d+)", block, re.M)
        parent = int(parent_m.group(1)) if parent_m else UNKNOWN_CARRIER_ID
        names[cid] = name
        for attr in re.findall(r"^  carrier_attribute \{\n(.*?)^  \}", block, re.S | re.M):
            fields = {f: [] for f in RULE_FIELDS}
            for key, val in re.findall(r'^\s+(\w+): "(.*)"$', attr, re.M):
                if key not in fields:
                    raise ValueError(f"unknown carrier attribute {key} (cid {cid})")
                fields[key].append(val.encode().decode("unicode_escape"))
            # CarrierIdProvider stores the cartesian product of the lists.
            combos = [[]]
            for f in RULE_FIELDS:
                opts = fields[f] or [None]
                combos = [c + [o] for c in combos for o in opts]
            for c in combos:
                rules.append(Rule(cid, name, parent, c))
    return names, rules


def resolve_carrier(rules: list[Rule], sim: dict):
    """CarrierResolver.matchSubscriptionCarrier(): -> (carrier_id, specific_id, mno_id)."""
    mccmnc = sim["mcc"] + sim["mnc"]

    def gid_match(sim_gid, gid):
        return sim_gid is not None and sim_gid.lower().startswith(gid.lower())

    def score(r: Rule):
        s = 0
        if r.mccmnc is not None:
            if r.mccmnc != mccmnc:
                return -1
            s += 1 << 8
        if r.imsi is not None:
            imsi = sim.get("imsi") or ""
            if len(imsi) < len(r.imsi) or any(
                    p not in "xX" and p != imsi[i] for i, p in enumerate(r.imsi)):
                return -1
            s += 1 << 7
        if r.iccid is not None:
            if not (sim.get("iccid") or "").startswith(r.iccid):
                return -1
            s += 1 << 6
        if r.gid1 is not None:
            if not gid_match(sim.get("gid1"), r.gid1):
                return -1
            s += 1 << 5
        if r.gid2 is not None:
            if not gid_match(sim.get("gid2"), r.gid2):
                return -1
            s += 1 << 4
        if r.plmn is not None:
            if (sim.get("plmn") or "").lower() != r.plmn.lower():
                return -1
            s += 1 << 3
        if r.spn is not None:
            if sim.get("spn") is None or sim["spn"].lower() != r.spn.lower():
                return -1
            s += 1 << 1
        if r.priv is not None:
            return -1  # we never emulate carrier-privileged SIM certificates
        if r.apn is not None:
            if (sim.get("apn") or "").lower() != r.apn.lower():
                return -1
            s += 1 << 0
        return s

    best = -1
    max_rule = max_parent = mno = None
    for r in (r for r in rules if r.mccmnc == mccmnc):
        r_score = score(r)
        if r_score > best:
            best, max_rule, max_parent = r_score, r, r
        elif best > -1 and r_score == best:
            if r.parent == max_rule.cid:
                max_rule = r
            elif max_rule.parent == r.cid:
                max_parent = r
        if r_score == 1 << 8:
            mno = r
    if best == -1:
        return UNKNOWN_CARRIER_ID, UNKNOWN_CARRIER_ID, UNKNOWN_CARRIER_ID
    parent_cid = max_parent.cid
    if max_rule is max_parent and max_rule.parent != UNKNOWN_CARRIER_ID:
        parent_cid = max_rule.parent
    return parent_cid, max_rule.cid, (mno.cid if mno else max_rule.cid)


def carrier_id_from_mccmnc(rules: list[Rule], mccmnc: str) -> int:
    """CarrierResolver.getCarrierIdFromMccMnc(): the rule that has only an MCC/MNC."""
    for r in rules:
        if r.mccmnc == mccmnc and all(v is None for v in (
                r.imsi, r.iccid, r.gid1, r.gid2, r.plmn, r.spn, r.priv, r.apn)):
            return r.cid
    return UNKNOWN_CARRIER_ID


