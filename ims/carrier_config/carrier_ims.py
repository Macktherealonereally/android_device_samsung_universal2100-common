def profile_has_settings(path: pathlib.Path) -> bool:
    return has_settings(ET.parse(path).getroot())


def xcap_tuples(apn_dir: pathlib.Path) -> set[str]:
    tuples = set()
    for f in sorted(apn_dir.glob("*.xml")):
        if f.name.endswith(".xsd"):
            continue
        for apn in ET.parse(f).getroot().iter("apn"):
            types = {t.strip() for t in (apn.get("type") or "").split(",")}
            if types & {"xcap", "*"}:
                tuples.add(apn.get("mcc") + apn.get("mnc"))
    return tuples


def split_mccmnc(tuple_: str) -> tuple[str, str]:
    return tuple_[:3], tuple_[3:]


def gather(top: pathlib.Path):
    policy = json.loads(POLICY.read_text())
    excluded_mcc = set(policy["exclude_mcc"])
    excluded = set(policy.get("exclude_mccmnc", {}))
    cs = top / CS_ASSETS
    cc = top / CC_ASSETS
    names, rules = parse_carrier_ids(top / CARRIER_IDS)

    manual_root = ET.parse(MANUAL).getroot()
    manual = set()
    for elem in manual_root.iter("carrier_config"):
        if "mcc" not in elem.attrib or "mnc" not in elem.attrib:
            raise SystemExit("manual.xml blocks must filter on mcc and mnc")
        manual.add(elem.get("mcc") + elem.get("mnc"))

    def skip(tuple_):
        return tuple_ in manual or tuple_[:3] in excluded_mcc or tuple_ in excluded

    # 1) Google CarrierSettings: the MCC/MNC-only entry (what an MNO SIM without
    #    GID1/SPN/IMSI selectors selects) names a profile with IMS settings.
    tuple_src: dict[str, list[str]] = {}
    seen_plain = set()
    for entry in ET.parse(cs / "carrier_settings/carrier_list.xml").getroot():
        attrs = dict(entry.attrib)
        profile = entry.find("string[@name='profile']").text
        if set(attrs) != {"mcc", "mnc"}:
            continue
        t = attrs["mcc"] + attrs["mnc"]
        if t in seen_plain:
            continue  # first match wins
        seen_plain.add(t)
        if profile_has_settings(cs / f"carrier_settings/profiles/{profile}.xml"):
            tuple_src.setdefault(t, []).append(f"google:{profile}")

    # 2) AOSP ImsStack profiles in CarrierSettings: MCC/MNC files and explicit
    #    MCC/MNC corrections apply to the whole MCC/MNC; carrier id files only to
    #    that carrier (filtered with cid as well).
    cid_src: dict[int, str] = {}
    for f in sorted((cs / "carrier_config").glob("*.xml")):
        m = re.fullmatch(r"carrier_config_(?:override_)?mccmnc_(\d{5,6})\.xml", f.name)
        if m:
            if profile_has_settings(f):
                tuple_src.setdefault(m.group(1), []).append(f"aosp:{f.name}")
            continue
        m = re.fullmatch(r"carrier_config_carrierid_(\d+)_.*\.xml", f.name)
        if m and profile_has_settings(f):
            cid_src[int(m.group(1))] = f"aosp:{f.name}"

    # Framework (AOSP CarrierConfig) facts we must not contradict.
    cc_cid = {}
    for f in sorted(cc.glob("carrier_config_carrierid_*.xml")):
        cc_cid[int(re.match(r"carrier_config_carrierid_(\d+)_", f.name).group(1))] = \
            read_config_list(ET.parse(f).getroot(), None, None)
    cc_tuple_any = {}
    for f in sorted(cc.glob("carrier_config_mccmnc_*.xml")):
        t = re.match(r"carrier_config_mccmnc_(\d+)\.xml", f.name).group(1)
        merged = {}
        for elem in ET.parse(f).getroot().iter("carrier_config"):
            for k, v in read_bundle(elem).items():
                merged.setdefault(k, set()).add(v)
        cc_tuple_any[t] = merged

    cids_on_tuple: dict[str, set[int]] = {}
    for r in rules:
        if r.mccmnc:
            cids_on_tuple.setdefault(r.mccmnc, set()).add(r.cid)
            if r.parent != UNKNOWN_CARRIER_ID:
                cids_on_tuple[r.mccmnc].add(r.parent)

    xcap = xcap_tuples(top / APN_DIR)
    return dict(names=names, rules=rules, manual=manual, skip=skip, tuple_src=tuple_src,
                cid_src=cid_src, cc_cid=cc_cid, cc_tuple_any=cc_tuple_any,
                cids_on_tuple=cids_on_tuple, xcap=xcap, policy=policy)


def cc_value(bundle: dict, key: str):
    v = bundle.get(key)
    return v[1] if v else None


def build_blocks(g):
    blocks = []  # (sort key, attrs, comment, settings, inventory row)
    notes = []

    def ut_cids(tuple_, cids):
        """Carriers whose AOSP CarrierConfig enables UT, on an MCC/MNC without XCAP APN."""
        # Carriers that AOSP CarrierConfig already runs with VoLTE keep their UT setting.
        if tuple_ in g["xcap"]:
            return []
        return sorted(c for c in cids
                      if cc_value(g["cc_cid"].get(c, {}), KEY_UT) == "true"
                      and cc_value(g["cc_cid"].get(c, {}), KEY_VOLTE) != "true")

    def ut_tuple(tuple_):
        values = g["cc_tuple_any"].get(tuple_, {})
        return tuple_ not in g["xcap"] and ("boolean", "true") in values.get(KEY_UT, set()) \
            and ("boolean", "true") not in values.get(KEY_VOLTE, set())

    for t in sorted(g["tuple_src"]):
        if g["skip"](t):
            continue
        cids = g["cids_on_tuple"].get(t, set())
        if ("boolean", "false") in g["cc_tuple_any"].get(t, {}).get(KEY_VOLTE, set()):
            notes.append(f"{t}: AOSP CarrierConfig MCC/MNC file disables VoLTE - left alone")
            continue
        mcc, mnc = split_mccmnc(t)
        settings = [(KEY_VOLTE, "true"), (KEY_PRECONDITION, "false")]
        ut = ut_tuple(t)
        if ut:
            settings.append((KEY_UT, "false"))
        ut_off = ut_cids(t, cids)
        names = sorted({g["names"][c] for c in cids if c in g["names"]})
        blocks.append(((mcc, mnc, 0), {"mcc": mcc, "mnc": mnc},
                       ", ".join(g["tuple_src"][t]), settings,
                       (mcc, mnc, "-", ";".join(g["tuple_src"][t]),
                        "off" if ut else (",".join(f"off:{c}" for c in ut_off) or "-"),
                        "; ".join(names))))
        for c in sorted(set(ut_off) | {c for c in cids
                                       if cc_value(g["cc_cid"].get(c, {}), KEY_VOLTE) == "false"}):
            extra = []
            if cc_value(g["cc_cid"].get(c, {}), KEY_VOLTE) == "false":
                extra.append((KEY_VOLTE, "false"))  # keep an explicit "no VoLTE"
                notes.append(f"{t} cid {c}: VoLTE kept off (AOSP CarrierConfig)")
            if c in ut_off:
                extra.append((KEY_UT, "false"))
            blocks.append(((mcc, mnc, c), {"mcc": mcc, "mnc": mnc, "cid": str(c)},
                           f"{g['names'].get(c, c)}: AOSP CarrierConfig "
                           + ("disables VoLTE" if (KEY_VOLTE, "false") in extra
                              else "enables UT, no XCAP APN: SS stays on CS"),
                           extra, None))

    for c in sorted(g["cid_src"]):
        tuples = sorted(t for t, cs_ in g["cids_on_tuple"].items() if c in cs_)
        for t in tuples:
            if g["skip"](t) or t in g["tuple_src"]:
                continue
            if cc_value(g["cc_cid"].get(c, {}), KEY_VOLTE) == "false":
                notes.append(f"{t} cid {c}: AOSP CarrierConfig disables VoLTE - left alone")
                continue
            mcc, mnc = split_mccmnc(t)
            settings = [(KEY_VOLTE, "true"), (KEY_PRECONDITION, "false")]
            ut = ut_tuple(t) or bool(ut_cids(t, {c}))
            if ut:
                settings.append((KEY_UT, "false"))
            blocks.append(((mcc, mnc, c), {"mcc": mcc, "mnc": mnc, "cid": str(c)},
                           g["cid_src"][c], settings,
                           (mcc, mnc, str(c), g["cid_src"][c], "off" if ut else "-",
                            g["names"].get(c, ""))))
    blocks.sort(key=lambda b: (b[0][0], b[0][1], b[0][2]))
    return blocks, notes


def xml_escape_comment(text: str) -> str:
    return text.replace("--", "- -")


def render(g, blocks) -> str:
    manual_text = MANUAL.read_text(encoding="utf-8")
    m = re.search(r"<carrier_config_list>\n(.*)</carrier_config_list>", manual_text, re.S)
    if not m:
        raise SystemExit("manual.xml: expected <carrier_config_list> ... </carrier_config_list>")
    out = [
        '<?xml version="1.0" encoding="utf-8" standalone="yes"?>',
        "<!--",
        "     SPDX-FileCopyrightText: The LineageOS Project",
        "     SPDX-License-Identifier: Apache-2.0",
        "",
        "     GENERATED FILE - edit ims/carrier_config/manual.xml or policy.json and run",
        "         python3 ims/carrier_config/carrier_ims.py generate",
        "     (see ims/carrier_config/README.md).",
        "",
        "     CarrierConfig (com.android.carrierconfig) reads this after its own assets;",
        "     every <carrier_config> whose filters match the SIM is applied in order.",
        "     Filter values must stay strings (aaptflags in Android.bp).",
        "-->",
        "<carrier_config_list>",
        "    <!-- Hand-verified carriers (manual.xml), copied verbatim. -->",
        m.group(1).rstrip("\n"),
        "",
        "    " + BEGIN,
        "    <!-- VoLTE for carriers with an IMS profile in packages/apps/CarrierSettings.",
        "         Preconditions off: the Samsung RIL reports no dedicated-bearer QoS.",
        "         carrier_supports_ss_over_ut_bool=false only where AOSP CarrierConfig",
        "         enables UT and LineageOS' APN database has no XCAP APN. No VoWiFi:",
        "         no profile carries ePDG data. -->",
    ]
    for _, attrs, comment, settings, _row in blocks:
        a = " ".join(f'{k}="{v}"' for k, v in attrs.items())
        out.append(f"    <carrier_config {a}>")
        out.append(f"        <!-- {xml_escape_comment(comment)} -->")
        for k, v in settings:
            out.append(f'        <boolean name="{k}" value="{v}" />')
        out.append("    </carrier_config>")
    out.append("    " + END)
    out.append("</carrier_config_list>")
    return "\n".join(out) + "\n"


def render_inventory(blocks) -> str:
    lines = ["# GENERATED by carrier_ims.py generate. VoLTE enabled by the generated part of",
             "# CarrierConfigOverlayIms vendor.xml (manual.xml carriers are not listed).",
             "# mcc\tmnc\tcarrier_id(- = whole MCC/MNC)\tsource\tss_over_ut\tcarrier names"]
    for *_, row in blocks:
        if row:
            lines.append("\t".join(row))
    return "\n".join(lines) + "\n"


def cmd_generate(args):
    top = pathlib.Path(args.top)
    g = gather(top)
    blocks, notes = build_blocks(g)
    xml_text = render(g, blocks)
    tsv_text = render_inventory(blocks)
    ET.fromstring(xml_text.encode())  # well-formed
    rows = [b[4] for b in blocks if b[4]]
    tuples = {(r[0], r[1]) for r in rows if r[2] == "-"}
    cid_rows = [r for r in rows if r[2] != "-"]
    summary = (f"manual MCC/MNCs: {len(g['manual'])}; generated: {len(tuples)} MCC/MNCs + "
               f"{len(cid_rows)} carrier-id blocks ({len(rows)} total); "
               f"UT kept on CS (rows): {sum(1 for r in rows if 'off' in r[4])}")
    if args.check:
        ok = OVERLAY_XML.read_text() == xml_text and INVENTORY.read_text() == tsv_text
        print(("up to date: " if ok else "OUT OF DATE: ") + summary)
        return 0 if ok else 1
    OVERLAY_XML.parent.mkdir(parents=True, exist_ok=True)
    OVERLAY_XML.write_text(xml_text)
    INVENTORY.write_text(tsv_text)
    for n in notes:
        print("note:", n)
    print(summary)
    return 0


