def _num(text: str | None) -> str:
    text = (text or "").strip()
    try:
        return str(int(text, 0) if text.lower().startswith(("0x", "-0x")) else int(text))
    except ValueError:
        return text


def _bool(text: str | None) -> str:
    return "true" if (text or "").strip().lower() == "true" else "false"


def read_bundle(elem) -> dict:
    """PersistableBundle.restoreFromXml() for one <carrier_config> element."""
    bundle = {}
    for child in elem:
        if not isinstance(child.tag, str):
            continue  # comments
        name = child.get("name")
        if name is None:
            continue
        tag = child.tag
        if tag == "boolean":
            value = _bool(child.get("value"))
        elif tag in ("int", "long"):
            value = _num(child.get("value"))
        elif tag == "double":
            value = repr(float(child.get("value")))
        elif tag == "string":
            value = child.text if child.text is not None else (child.get("value") or "")
        elif tag in ("int-array", "long-array"):
            value = tuple(_num(i.get("value")) for i in child if i.tag == "item")
        elif tag == "boolean-array":
            value = tuple(_bool(i.get("value")) for i in child if i.tag == "item")
        elif tag == "double-array":
            value = tuple(repr(float(i.get("value"))) for i in child if i.tag == "item")
        elif tag == "string-array":
            value = tuple((i.get("value") or "") for i in child if i.tag == "item")
        elif tag == "pbundle_as_map":
            value = tuple(sorted(read_bundle(child).items()))
        else:
            raise ValueError(f"unsupported bundle tag <{tag} name={name!r}>")
        bundle[name] = (tag, value)
    return bundle


def has_settings(elem) -> bool:
    return any(isinstance(c.tag, str) and c.get("name") for c in elem)


def parse_xml_text(text: str):
    return ET.fromstring(text.encode("utf-8") if isinstance(text, str) else text)


# aapt2 "dump xmltree" output -> ElementTree, using the raw attribute strings
# (the CarrierConfig RRO is built with --keep-raw-values, so the runtime parser
# sees exactly these strings).
_AAPT_E = re.compile(r"^(\s*)E: (\S+) \(line=\d+\)$")
_AAPT_A = re.compile(r'^(\s*)A: (?:[^=]*:)?([^=:\s]+)(?:\(0x[0-9a-f]+\))?=(.*?)(?: \(Raw: "(.*)"\))?$')
_AAPT_T = re.compile(r"^(\s*)T: '(.*)'$", re.S)


def parse_aapt2_xmltree(dump: str):
    root = None
    stack: list[tuple[int, ET.Element]] = []
    for line in dump.splitlines():
        if not line.strip() or line.lstrip().startswith("N:"):
            continue
        m = _AAPT_E.match(line)
        if m:
            depth = len(m.group(1))
            while stack and stack[-1][0] >= depth:
                stack.pop()
            elem = ET.Element(m.group(2))
            if stack:
                stack[-1][1].append(elem)
            else:
                root = elem
            stack.append((depth, elem))
            continue
        m = _AAPT_A.match(line)
        if m:
            raw = m.group(4)
            if raw is None:
                raw = m.group(3).strip().strip('"')
            stack[-1][1].set(m.group(2), raw)
            continue
        m = _AAPT_T.match(line)
        if m:
            depth = len(m.group(1))
            while stack and stack[-1][0] >= depth:
                stack.pop()
            stack[-1][1].text = (stack[-1][1].text or "") + m.group(2)
            continue
        raise ValueError(f"cannot parse aapt2 line: {line!r}")
    return root


