# Input sources: a directory, an APK, or an APK inside a target-files zip
# --------------------------------------------------------------------------

class Source:
    """Read files from a directory or a zip (optionally a zip inside a zip)."""

    def __init__(self, spec: str):
        self.spec = spec
        self.dir = None
        self.zip = None
        if "!" in spec:  # outer.zip!inner/path.apk
            outer, inner = spec.split("!", 1)
            with zipfile.ZipFile(outer) as z:
                data = z.read(inner)
            self.zip = zipfile.ZipFile(io.BytesIO(data))
            self.blob = data
        elif pathlib.Path(spec).is_dir():
            self.dir = pathlib.Path(spec)
        else:
            self.blob = pathlib.Path(spec).read_bytes()
            self.zip = zipfile.ZipFile(io.BytesIO(self.blob))

    def list(self, prefix: str = "") -> list[str]:
        if self.dir is not None:
            base = self.dir / prefix if prefix else self.dir
            return sorted(p.name for p in base.iterdir() if p.is_file())
        names = set()
        for n in self.zip.namelist():
            if n.startswith(prefix) and "/" not in n[len(prefix):]:
                names.add(n[len(prefix):])
        return sorted(names)

    def read(self, path: str) -> bytes:
        if self.dir is not None:
            return (self.dir / path).read_bytes()
        return self.zip.read(path)


def load_vendor_xml(spec: str, aapt2: str | None):
    """vendor.xml from a source XML file or from a built RRO APK (aapt2 dump)."""
    if spec.endswith(".xml") and "!" not in spec:
        return ET.parse(spec).getroot()
    src = Source(spec)
    if not aapt2:
        raise SystemExit("--aapt2 is needed to read a compiled overlay APK")
    with tempfile.TemporaryDirectory() as tmpdir:
        tmp = pathlib.Path(tmpdir) / "overlay.apk"
        tmp.write_bytes(src.blob)
        dump = subprocess.run(
            [aapt2, "dump", "xmltree", "--file", "res/xml/vendor.xml", str(tmp)],
            check=True, capture_output=True, text=True).stdout
    return parse_aapt2_xmltree(dump)


