"""VoLTE enablement for the open-source IMS stack, plus a CarrierConfig emulator.

ImsStack (packages/modules/ImsStack) only starts VoLTE when Android's own
CarrierConfig says carrier_volte_available_bool=true. Its CarrierSettings APK
(packages/apps/CarrierSettings) carries IMS profiles for hundreds of carriers,
but on purpose never sets that service flag, and AOSP CarrierConfig enables it
for only a few carriers. This tool closes the gap with one generated
CarrierConfig vendor.xml (static RRO): VoLTE on for every carrier that has a
real IMS profile in CarrierSettings, plus the hand-verified blocks from
manual.xml. See README.md next to this file.

Subcommands:
  generate [--check]  write (or verify) the overlay's vendor.xml + volte_carriers.tsv
  effective           print the bundle com.android.carrierconfig returns for one SIM
  diff                compare that bundle for a list of SIMs between two inputs

Inputs can be source trees or built artifacts (APK / target-files paths), so the
same emulator proves what a release build really ships. Standard library only.
"""

