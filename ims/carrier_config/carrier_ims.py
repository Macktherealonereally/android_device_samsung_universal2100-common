def effective_lines(cc_spec, vendor_spec, sim, rules, aapt2):
    cc = Source(cc_spec)
    vendor_root = load_vendor_xml(vendor_spec, aapt2)
    ids = sim_ids(rules, sim)
    return ids, format_bundle(load_config(cc, vendor_root, sim, ids))


def cmd_effective(args):
    _, rules = parse_carrier_ids(pathlib.Path(args.top) / CARRIER_IDS)
    sim = {k: v for k, v in vars(args).items()
           if k in ("mcc", "mnc", "spn", "gid1", "gid2", "imsi") and v is not None}
    ids, lines = effective_lines(args.carrierconfig, args.vendor, sim, rules, args.aapt2)
    print(f"# {sim} -> {ids}")
    print("\n".join(lines))
    return 0


def cmd_diff(args):
    _, rules = parse_carrier_ids(pathlib.Path(args.top) / CARRIER_IDS)
    sims = json.loads(pathlib.Path(args.sims).read_text())
    before_cc = Source(args.before_carrierconfig)
    after_cc = Source(args.after_carrierconfig or args.before_carrierconfig)
    before_v = load_vendor_xml(args.before_vendor, args.aapt2)
    after_v = load_vendor_xml(args.after_vendor, args.aapt2)
    print(f"before: {args.before_carrierconfig} + {args.before_vendor}")
    print(f"after:  {args.after_carrierconfig or args.before_carrierconfig} + {args.after_vendor}")
    changed_unexpected = 0
    for sim in sims:
        label = sim.pop("label")
        expect = sim.pop("expect", None)
        ids = sim_ids(rules, sim)
        b = format_bundle(load_config(before_cc, before_v, sim, ids))
        a = format_bundle(load_config(after_cc, after_v, sim, ids))
        hb = hashlib.sha256("\n".join(b).encode()).hexdigest()[:16]
        ha = hashlib.sha256("\n".join(a).encode()).hexdigest()[:16]
        same = a == b
        status = "IDENTICAL" if same else "CHANGED"
        flag = ""
        if expect and expect != status.lower():
            flag = "   <-- UNEXPECTED"
            changed_unexpected += 1
        print(f"\n== {label}: {sim} carrier_id={ids['carrier_id']} "
              f"specific={ids['specific_carrier_id']}")
        print(f"   {status}  keys {len(b)} -> {len(a)}  sha256 {hb} -> {ha}{flag}")
        if not same:
            sb, sa = set(b), set(a)
            for line in sorted(sb - sa):
                print(f"   - {line}")
            for line in sorted(sa - sb):
                print(f"   + {line}")
    return 1 if changed_unexpected else 0


