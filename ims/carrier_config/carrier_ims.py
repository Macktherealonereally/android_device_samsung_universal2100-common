def check_filters(elem, sim: dict | None, cids: tuple[int, int] | None) -> bool:
    for attr, value in elem.attrib.items():
        if sim is None:
            if attr in ("mcc", "mnc", "gid1", "gid2", "spn", "imsi", "cid", "name"):
                continue
        if attr == "mcc":
            ok = value == sim["mcc"]
        elif attr == "mnc":
            ok = value == sim["mnc"]
        elif attr == "gid1":
            ok = sim.get("gid1") is not None and value.lower() == sim["gid1"].lower()
        elif attr == "gid2":
            ok = sim.get("gid2") is not None and value.lower() == sim["gid2"].lower()
        elif attr == "spn":
            if value.lower() == "null":
                ok = not sim.get("spn")
            else:
                ok = sim.get("spn") is not None and re.fullmatch(value, sim["spn"], re.I) is not None
        elif attr == "imsi":
            ok = sim.get("imsi") is not None and re.fullmatch(value, sim["imsi"], re.I) is not None
        elif attr == "cid":
            ok = int(value) in cids
        elif attr == "name":
            ok = True
        else:
            # device/board/sku filters: never used by this tree's files
            raise ValueError(f"unsupported filter {attr}={value!r}")
        if not ok:
            return False
    return True


def read_config_list(root, sim, cids) -> dict:
    """readConfigFromXml(): flatten every matching <carrier_config> in document order."""
    config = {}
    elems = [root] if root.tag == "carrier_config" else list(root.iter("carrier_config"))
    for elem in elems:
        if check_filters(elem, sim, cids):
            config.update(read_bundle(elem))
    return config


def load_config(cc: Source, vendor_root, sim: dict, ids: dict) -> dict:
    cid, specific = ids["carrier_id"], ids["specific_carrier_id"]
    mccmnc_cid = ids["mccmnc_carrier_id"]
    config = {}
    if cid != UNKNOWN_CARRIER_ID:
        by_specific, by_cid, by_mccmnc = {}, {}, {}
        for name in cc.list("assets/" if cc.dir is None else ""):
            path = ("assets/" if cc.dir is None else "") + name
            if name.startswith(f"carrier_config_carrierid_{specific}_"):
                by_specific = read_config_list(parse_xml_text(cc.read(path)), None, None)
                break
            elif name.startswith(f"carrier_config_carrierid_{cid}_"):
                by_cid = read_config_list(parse_xml_text(cc.read(path)), None, None)
            elif name.startswith(f"carrier_config_carrierid_{mccmnc_cid}_"):
                by_mccmnc = read_config_list(parse_xml_text(cc.read(path)), None, None)
        config = by_specific or by_cid or by_mccmnc
    if not config:
        path = ("assets/" if cc.dir is None else "") + f"carrier_config_mccmnc_{sim['mcc']}{sim['mnc']}.xml"
        try:
            config = read_config_list(parse_xml_text(cc.read(path)), sim, (cid, specific))
        except (KeyError, FileNotFoundError):
            config = {}
    config = dict(config)
    config.update(read_config_list(vendor_root, sim, (cid, specific)))
    return config


def format_bundle(bundle: dict) -> list[str]:
    def fmt(tag, value):
        if tag == "pbundle_as_map":
            return "{" + ", ".join(f"{k}={fmt(*v)}" for k, v in value) + "}"
        if isinstance(value, tuple):
            return "[" + ", ".join(value) + "]"
        return value
    return [f"{k} = {tag}:{fmt(tag, value)}" for k, (tag, value) in sorted(bundle.items())]


def sim_ids(rules, sim):
    if "carrier_id" in sim:
        cid = int(sim["carrier_id"])
        specific = int(sim.get("specific_carrier_id", cid))
    else:
        cid, specific, _ = resolve_carrier(rules, sim)
    return {"carrier_id": cid, "specific_carrier_id": specific,
            "mccmnc_carrier_id": carrier_id_from_mccmnc(rules, sim["mcc"] + sim["mnc"])}


